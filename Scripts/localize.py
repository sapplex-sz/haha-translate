#!/usr/bin/env python3
"""Generate and validate the explicit app localization catalogs; no network access."""
from pathlib import Path
import argparse, json, re, plistlib
ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'Scripts/Localization'
LANGUAGES = ['en', 'zh-Hans', 'zh-Hant', 'ja', 'ko', 'fr', 'de', 'es', 'pt', 'ru', 'it']
INFO_KEYS = ['HaHa翻译', '在你主动选择截图翻译时，读取所选屏幕区域并在本机识别文字。截图不会上传。', '使用HaHa翻译', '本机处理选中文字并显示译文。']
FORMAT = re.compile(r'%(?:(\d+)\$)?[-+# 0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(hh|ll|h|l|L|z|t|j)?([@diuoxXfFeEgGaAcCsSp%])')
def placeholders(value):
    result = {}
    next_argument = 1
    for m in FORMAT.finditer(value):
        if m.group(3) == '%': continue
        position = int(m.group(1)) if m.group(1) else next_argument
        kind = (m.group(2) or '', m.group(3))
        if position in result and result[position] != kind:
            raise ValueError(f'Conflicting format types for argument {position}')
        result[position] = kind
        next_argument += 1
    return result
def quote(value): return json.dumps(value,ensure_ascii=False).replace('\\/', '/')
def write_strings(path, mapping):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('// Generated by Scripts/localize.py. Edit Scripts/Localization/*.json.\n'+'\n'.join(f'{quote(k)} = {quote(v)};' for k,v in sorted(mapping.items()))+'\n')
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');parser.add_argument('--bootstrap',action='store_true',help='Generate only en/zh-Hans for development before other catalogs are complete')
    args=parser.parse_args()
    english=json.loads((CATALOG/'en.json').read_text());keys=set(english);used=set()
    for path in (ROOT/'Sources').rglob('*.swift'):
        for match in re.finditer(r'\bL\("((?:[^"\\]|\\.)*)"',path.read_text()):
            literal=match.group(1)
            if '\\(' in literal: raise SystemExit(f'Dynamic localization key in {path}: {literal}')
            used.add(json.loads('"'+literal+'"'))
    missing=(used|set(INFO_KEYS))-keys
    if missing: raise SystemExit('English catalog missing: '+json.dumps(sorted(missing),ensure_ascii=False))
    errors=[];counts={};catalogs={}
    declared=plistlib.loads((ROOT/"Config/Info.plist").read_bytes()).get("CFBundleLocalizations",[])
    if set(declared)!=set(LANGUAGES): errors.append("Info.plist languages do not match catalog languages")
    interface=set(re.findall(r'.init\(id: "([^"]+)"', (ROOT/"Sources/Core/Localization.swift").read_text()))-{"system"}
    if interface!=set(LANGUAGES): errors.append("Interface language choices do not match catalog languages")
    for language in (['en','zh-Hans'] if args.bootstrap else LANGUAGES):
        path=CATALOG/f'{language}.json'
        if language=='zh-Hans': data={k:k for k in keys}
        elif path.exists(): data=json.loads(path.read_text())
        else: errors.append(f'{language}: missing catalog');continue
        missing=keys-set(data);extra=set(data)-keys
        if missing: errors.append(f'{language}: missing {len(missing)} keys: '+json.dumps(sorted(missing),ensure_ascii=False));continue
        if extra: errors.append(f'{language}: extra {len(extra)} keys');continue
        for key,value in data.items():
            if not isinstance(value,str) or not value.strip():errors.append(f'{language}: empty value for {key}')
            elif placeholders(value)!=placeholders(english[key]):errors.append(f'{language}: format mismatch for {key}')
        counts[language]=len(data)
        catalogs[language]=data
    if errors:raise SystemExit("\n".join(errors))
    for language,data in catalogs.items():
        folder=ROOT/'Resources'/f'{language}.lproj'
        if args.write:
            write_strings(folder/'Localizable.strings',data)
            write_strings(folder/'InfoPlist.strings',{'CFBundleDisplayName':data['HaHa翻译'],'CFBundleName':data['HaHa翻译'],'NSScreenCaptureUsageDescription':data[INFO_KEYS[1]]})
            write_strings(folder/'ServicesMenu.strings',{'Translate with HaHa':data['使用HaHa翻译'],'TRANSLATE_SELECTION_DESCRIPTION':data['本机处理选中文字并显示译文。']})
        expected = {
            'Localizable.strings': data,
            'InfoPlist.strings': {'CFBundleDisplayName':data['HaHa翻译'],'CFBundleName':data['HaHa翻译'],'NSScreenCaptureUsageDescription':data[INFO_KEYS[1]]},
            'ServicesMenu.strings': {'Translate with HaHa':data['使用HaHa翻译'],'TRANSLATE_SELECTION_DESCRIPTION':data['本机处理选中文字并显示译文。']}
        }
        for filename, mapping in expected.items():
            target=folder/filename
            if not target.exists(): errors.append(f'{language}/{filename}: not generated');continue
            actual={json.loads(k):json.loads(v) for k,v in re.findall(r'^("(?:[^"\\]|\\.)*") = ("(?:[^"\\]|\\.)*");$',target.read_text(),re.MULTILINE)}
            if actual!=mapping: errors.append(f'{language}/{filename}: differs from catalog; run --write')
    if errors:raise SystemExit('\n'.join(errors))
    print(f'PASS: {len(used)} source keys; {len(keys)} catalog keys; complete catalogs {counts}; placeholders matched.')
    if args.bootstrap:print('Development bootstrap only; this does not certify all declared languages.')
if __name__=='__main__':main()
